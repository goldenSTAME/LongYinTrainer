param(
    [string]$GamePath = (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent),
    [switch]$Startup,
    [int]$StartupTimeoutSeconds = 90
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$GamePath = (Resolve-Path -LiteralPath $GamePath).Path
if (Get-Process LongYinLiZhiZhuan -ErrorAction SilentlyContinue) { throw 'Close the game before running checks.' }
$out = Join-Path $root ('test-results/' + (Get-Date -Format 'yyyyMMdd-HHmmss'))
New-Item -ItemType Directory -Path $out -Force | Out-Null
$results = [System.Collections.Generic.List[object]]::new()
function Result($name, $status, $detail) {
    $results.Add([pscustomobject]@{ Case=$name; Status=$status; Detail=$detail })
    Write-Host "$status $name : $detail"
}
function Manifest($path) {
    $map = [ordered]@{}
    if (Test-Path -LiteralPath $path) {
        Get-ChildItem -LiteralPath $path -File -Recurse | Sort-Object FullName | ForEach-Object {
            $map[$_.FullName.Substring($path.Length)] = (Get-FileHash -LiteralPath $_.FullName).Hash
        }
    }
    return ($map | ConvertTo-Json -Compress)
}
$save = Join-Path $GamePath 'LongYinLiZhiZhuan_Data/Save'
$before = Manifest $save
$before | Set-Content (Join-Path $out 'save-before.json')
try {
    $build = & dotnet build (Join-Path $root 'LongYinTrainer/LongYinTrainer.csproj') -c Release "-p:GamePath=$GamePath" --nologo 2>&1
    $code = $LASTEXITCODE
    $build | Set-Content (Join-Path $out 'build.log')
    Result 'BUILD' $(if ($code -eq 0) {'PASS'} else {'FAIL'}) "exit=$code; build.log"
    # Discover complete regression projects, including local suites not yet tracked by git.
    $projects = Get-ChildItem -LiteralPath $root -Directory -Filter '*Regression' | ForEach-Object { Get-ChildItem -LiteralPath $_.FullName -Filter '*.csproj' }
    foreach ($project in $projects) {
        $log = & dotnet run --project $project.FullName -c Release "-p:GamePath=$GamePath" 2>&1
        $exit = $LASTEXITCODE
        $log | Set-Content (Join-Path $out ($project.BaseName + '.log'))
        $passes = @($log | Where-Object { "$_" -match '^PASS\b' }).Count
        Result $project.BaseName $(if ($exit -eq 0) {'PASS'} else {'FAIL'}) "exit=$exit; $passes named PASS cases; $($project.BaseName).log"
    }
    if ($Startup -and $code -eq 0) {
        $built = Join-Path $root 'LongYinTrainer/bin/Release/net6.0/LongYinTrainer.dll'
        $installed = Join-Path $GamePath 'BepInEx/plugins/LongYinTrainer.dll'
        if ((Get-FileHash $built).Hash -ne (Get-FileHash $installed).Hash) {
            Result 'DEPLOYED_BUILD' 'FAIL' 'Installed DLL differs from build. Deploy reviewed build before startup test.'
        } else {
            Result 'DEPLOYED_BUILD' 'PASS' (Get-FileHash $installed).Hash
            $logPath = Join-Path $GamePath 'BepInEx/LogOutput.log'
            if (Test-Path $logPath) { Copy-Item $logPath (Join-Path $out 'previous-startup.log') }
            $oldApp = $env:SteamAppId; $oldGame = $env:SteamGameId
            $proc = $null
            try {
                $env:SteamAppId = '3202030'; $env:SteamGameId = '3202030'
                $started = Get-Date
                $proc = Start-Process -FilePath (Join-Path $GamePath 'LongYinLiZhiZhuan.exe') -WorkingDirectory $GamePath -ArgumentList '-batchmode','-nographics','-quit' -WindowStyle Hidden -PassThru
                $deadline = $started.AddSeconds($StartupTimeoutSeconds)
                $readyAt = $null; $fresh = $false; $text = ''
                do {
                    Start-Sleep -Seconds 2
                    if ((Test-Path $logPath) -and (Get-Item $logPath).LastWriteTime -gt $started) {
                        $fresh = $true; $text = Get-Content $logPath -Raw
                        if ($text -match 'Chainloader startup complete' -and $null -eq $readyAt) { $readyAt = Get-Date }
                    }
                    $proc.Refresh()
                    if ($proc.HasExited -or ($readyAt -and (Get-Date) -gt $readyAt.AddSeconds(10))) { break }
                } while ((Get-Date) -lt $deadline)
                $text | Set-Content (Join-Path $out 'startup.log')
                Result 'FRESH_STARTUP_LOG' $(if ($fresh) {'PASS'} else {'FAIL'}) 'Only logs generated by this run are accepted.'
                $loaded = $fresh -and $text -match 'LongYin Trainer loaded\.' -and $text -match 'Chainloader startup complete'
                Result 'PLUGIN_LOAD' $(if ($loaded) {'PASS'} else {'FAIL'}) 'Trainer and chainloader completion markers required.'
                $errors = @($text -split "`n" | Where-Object { $_ -match '\[Error|\[Fatal|Method not found|Could not find method|MissingMethodException|Constructor not found' })
                Result 'PATCH_BINDINGS' $(if ($fresh -and $errors.Count -eq 0) {'PASS'} else {'FAIL'}) ($errors -join '; ')
                $warnings = @($text -split "`n" | Where-Object { $_ -match '\[Warning' })
                Result 'STARTUP_WARNINGS' $(if ($warnings.Count) {'WARN'} else {'PASS'}) ($warnings -join '; ')
                Result 'CUSTOM_DEFINITIONS' $(if ($text -match 'Registered \d+ custom kungfu definitions') {'PASS'} else {'SKIP'}) 'Runtime registration only; does not prove save round-trip compatibility.'
            } finally {
                if ($proc) { $proc.Refresh(); if (!$proc.HasExited) { Stop-Process -Id $proc.Id } }
                $env:SteamAppId=$oldApp; $env:SteamGameId=$oldGame
            }
        }
    } else { Result 'GAME_STARTUP' 'SKIP' 'Use -Startup after deploying the built DLL.' }
} catch { Result 'HARNESS' 'FAIL' $_.Exception.Message }
finally {
    $after = Manifest $save
    $after | Set-Content (Join-Path $out 'save-after.json')
    Result 'SAVE_UNCHANGED' $(if ($before -ceq $after) {'PASS'} else {'FAIL'}) 'SHA256 of every save file before/after; no save is loaded by this harness.'
    foreach ($case in @('H_PANEL_AND_PAGING','OLD_SAVE_LOAD_SAVE_RELOAD','NATIVE_AND_MOD_CUSTOM_KUNGFU','REAL_BATTLE_AND_REINFORCEMENTS')) {
        Result $case 'PENDING' 'Requires isolated game session and behavioral assertions; not covered by startup or mocks.'
    }
    $results | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $out 'results.json')
    $report = @('# Compatibility test results', '', "Run: $(Get-Date -Format o)", '', '| Case | Status | Detail |','| --- | --- | --- |')
    $report += $results | ForEach-Object { '| ' + $_.Case + ' | ' + $_.Status + ' | ' + ($_.Detail -replace '\|','/' -replace '[\r\n]+',' ') + ' |' }
    $report += @('', '## Executed regression cases', '')
    Get-ChildItem -LiteralPath $out -Filter '*Regression.log' | ForEach-Object {
        $report += @('', "### $($_.BaseName)", '')
        $report += Get-Content $_.FullName | Where-Object { $_ -match '^PASS\b|checks passed|catalog checks' } | ForEach-Object { '- ' + $_ }
    }
    $report | Set-Content (Join-Path $out 'REPORT.md')
    Write-Host "Report: $out"
}
if (@($results | Where-Object Status -eq 'FAIL').Count) { exit 1 }
